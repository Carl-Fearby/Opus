import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const applicationDirectory = path.resolve(scriptDirectory, "..");
const repositoryDirectory = path.resolve(applicationDirectory, "..");
const outputPath = path.join(applicationDirectory, "lib/generated/repositoryStats.ts");
const outputRelativePath = path.relative(repositoryDirectory, outputPath);

const languageDefinitions = [
  { label: "TypeScript", extensions: new Set([".ts", ".tsx"]) },
  { label: "CSS", extensions: new Set([".css", ".less", ".sass", ".scss"]) },
  { label: "JavaScript", extensions: new Set([".cjs", ".js", ".jsx", ".mjs"]) },
  { label: "Other", extensions: new Set([".htm", ".html", ".sh", ".svg"]) },
];

const trackedFiles = execFileSync(
  "git",
  ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
  {
    cwd: repositoryDirectory,
    encoding: "utf8",
  },
)
  .split("\0")
  .filter((file) => file && file !== outputRelativePath);

const languages = languageDefinitions.map(({ label, extensions }) => {
  let files = 0;
  let lines = 0;

  for (const relativePath of trackedFiles) {
    if (!extensions.has(path.extname(relativePath).toLowerCase())) continue;

    const contents = readFileSync(path.join(repositoryDirectory, relativePath), "utf8");
    files += 1;
    lines += contents.length === 0 ? 0 : contents.split(/\r?\n/).length;
  }

  return { label, files, lines };
});

const totalLines = languages.reduce((sum, language) => sum + language.lines, 0);
const output = `// Generated by scripts/generate-repository-stats.mjs — do not edit by hand.\n` +
  `export const repositoryStats = ${JSON.stringify({ totalLines, languages }, null, 2)} as const;\n`;

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, output);
console.log(`Updated ${outputRelativePath} (${totalLines.toLocaleString("en-GB")} source lines).`);

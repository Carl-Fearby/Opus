#!/usr/bin/env node
/**
 * Stamps the opus-react version the site should advertise.
 *
 * The library package is the source of truth, so a release never has to be
 * re-typed into the marketing site. The installed copy is only a fallback for
 * builds that do not have the monorepo checkout next to this app.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appDir = join(scriptDir, "..");
const libraryPackage = join(appDir, "..", "Library", "packages", "opus-react", "package.json");
const installedPackage = join(appDir, "node_modules", "opus-react", "package.json");
const target = join(appDir, "lib", "generated", "libraryVersion.ts");

function readVersion(file) {
  try {
    const pkg = JSON.parse(readFileSync(file, "utf8"));
    return typeof pkg.version === "string" && pkg.version ? pkg.version : null;
  } catch {
    return null;
  }
}

const version =
  (existsSync(libraryPackage) ? readVersion(libraryPackage) : null) ??
  readVersion(installedPackage);

if (!version) {
  console.error(
    "sync-library-version: could not read a version from Library/packages/opus-react/package.json or node_modules/opus-react/package.json",
  );
  process.exit(1);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  [
    "// Generated by scripts/sync-library-version.mjs — do not edit by hand.",
    "// Mirrors Library/packages/opus-react/package.json so the site always reports the library version.",
    "",
    `export const libraryVersion = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
);

console.log(`sync-library-version: libraryVersion = ${version}`);

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { locales } from "../lib/i18n/config";
import { componentMessages } from "../lib/i18n/componentMessages";
import { componentUiMessagesEn } from "../lib/i18n/componentUiMessages.en";

const componentsDir = join(process.cwd(), "components");
const outputPath = join(process.cwd(), "packages", "opus-react", "src", "i18nManifest.ts");

/** A literal `t("key", "fallback")` call: the key contract components rely on. */
const CALL_SITE_PATTERN =
  /\bt\(\s*(["'])([A-Za-z][\w-]*(?:\.[\w-]+)+)\1\s*,\s*(["'])((?:\\.|(?!\3)[\s\S])*)\3/g;

/** A `t(`namespace.${value}`)` call: its keys cannot be listed ahead of time. */
const DYNAMIC_KEY_PATTERN = /\bt\(\s*`([A-Za-z][\w-]*\.)[^`]*\$\{/g;

export type OpusTranslationManifestEntry = {
  fallback: string;
  shipped: boolean;
};

export type OpusTranslationContract = {
  entries: Map<string, OpusTranslationManifestEntry>;
  /** The first fallback seen at a call site for each key. */
  fallbacks: Map<string, string>;
  /** Keys whose call sites pass different English fallbacks. */
  conflicts: string[];
  dynamicPrefixes: string[];
  callSiteCount: number;
};

function componentFiles(dir: string, files: string[] = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      componentFiles(full, files);
      continue;
    }

    if (!/\.tsx?$/.test(entry.name)) continue;
    if (/\.test\./.test(entry.name) || /\.d\.ts$/.test(entry.name)) continue;
    if (!statSync(full).isFile()) continue;
    files.push(full);
  }

  return files;
}

function decodeFallback(raw: string) {
  return raw.replace(/\\n/g, "\n").replace(/\\"/g, '"').replace(/\\'/g, "'").replace(/\\\\/g, "\\");
}

/**
 * Builds the key contract from the components themselves: every literal
 * `t(key, fallback)` call site, plus every key that already ships a
 * translation (some components resolve keys through data tables, e.g.
 * `t(item.labelKey, item.label)`).
 */
export function readTranslationContract(): OpusTranslationContract {
  const entries = new Map<string, OpusTranslationManifestEntry>();
  const fallbacks = new Map<string, string>();
  const conflicts = new Set<string>();
  const dynamicPrefixes = new Set<string>();
  let callSiteCount = 0;

  for (const file of componentFiles(componentsDir)) {
    const source = readFileSync(file, "utf8");

    for (const match of source.matchAll(CALL_SITE_PATTERN)) {
      callSiteCount += 1;
      const key = match[2];
      const fallback = decodeFallback(match[4]);
      const seen = fallbacks.get(key);

      if (seen === undefined) {
        fallbacks.set(key, fallback);
        entries.set(key, { fallback, shipped: false });
      } else if (seen !== fallback) {
        conflicts.add(key);
      }
    }

    for (const match of source.matchAll(DYNAMIC_KEY_PATTERN)) {
      dynamicPrefixes.add(match[1]);
    }
  }

  // The English dictionary is the authoritative copy wherever it has an entry:
  // it is what every locale is translated from and what English renders.
  for (const [key, fallback] of Object.entries(componentUiMessagesEn)) {
    entries.set(key, { fallback, shipped: false });
  }

  // A key counts as shipped only when no locale is left untranslated.
  const shippedKeys = new Set(entries.keys());

  for (const { id } of locales) {
    const dictionary = componentMessages[id];

    for (const key of [...shippedKeys]) {
      const value = dictionary?.[key];
      if (typeof value !== "string" || value.trim() === "") {
        shippedKeys.delete(key);
      }
    }
  }

  for (const [key, entry] of entries) {
    entry.shipped = shippedKeys.has(key);
  }

  return {
    entries,
    fallbacks,
    conflicts: [...conflicts].sort(),
    dynamicPrefixes: [...dynamicPrefixes].sort(),
    callSiteCount,
  };
}

export function renderManifest(contract: OpusTranslationContract) {
  const pairs = [...contract.entries.entries()].sort(([left], [right]) =>
    left < right ? -1 : left > right ? 1 : 0,
  );
  const keys = pairs.map(([key]) => key);
  const shipped = pairs.filter(([, entry]) => entry.shipped).map(([key]) => key);
  const lines = pairs.map(
    ([key, entry]) =>
      `  ${JSON.stringify(key)}: { fallback: ${JSON.stringify(
        entry.fallback,
      )}, shipped: ${entry.shipped} },`,
  );

  return `// Generated by scripts/generate-i18n-manifest.ts — do not edit by hand.
// Run \`npm run generate:i18n-manifest\` after changing component copy or dictionaries.
//
// The translation contract: every key the library resolves through
// t(key, fallback). \`fallback\` is the English copy used when no translation is
// supplied, and \`shipped\` marks the keys translated in every locale. Use
// auditOpusTranslations to find keys a host dictionary is missing.

export type OpusTranslationManifestEntry = {
  /** English copy used when no translation is supplied for the key. */
  fallback: string;
  /** True when every shipped locale translates the key. */
  shipped: boolean;
};

export const opusTranslationManifest: Readonly<
  Record<string, OpusTranslationManifestEntry>
> = {
${lines.join("\n")}
};

/** Every key the library resolves, sorted. */
export const opusTranslationKeys: readonly string[] = [
${keys.map((key) => `  ${JSON.stringify(key)},`).join("\n")}
];

/** Keys translated in every shipped locale. */
export const opusTranslatedKeys: readonly string[] = [
${shipped.map((key) => `  ${JSON.stringify(key)},`).join("\n")}
];

/** Namespaces assembled at runtime, so their keys cannot be enumerated. */
export const opusDynamicTranslationPrefixes: readonly string[] = [
${contract.dynamicPrefixes.map((prefix) => `  ${JSON.stringify(prefix)},`).join("\n")}
];
`;
}

function main() {
  const check = process.argv.includes("--check");
  const contract = readTranslationContract();
  const next = renderManifest(contract);
  const shipped = [...contract.entries.values()].filter((entry) => entry.shipped).length;

  if (check) {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      current = "";
    }

    if (current === next) {
      console.log(
        `i18n manifest is up to date: ${contract.entries.size} keys (${shipped} translated in every locale).`,
      );
      return;
    }

    console.error(
      `i18n manifest is stale: ${relative(process.cwd(), outputPath)} does not match the ${contract.entries.size} keys in the components.`,
    );
    console.error("Run `npm run generate:i18n-manifest` to refresh it.");
    process.exit(1);
  }

  writeFileSync(outputPath, next);
  console.log(`Read ${contract.callSiteCount} t(key, fallback) call sites.`);
  console.log(
    `Wrote ${contract.entries.size} keys (${shipped} translated in every locale, ${contract.dynamicPrefixes.length} runtime namespace(s)) to ${relative(
      process.cwd(),
      outputPath,
    )}`,
  );
}

const invokedPath = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (invokedPath === import.meta.url) {
  main();
}
